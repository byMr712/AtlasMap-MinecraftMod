def gen_ruler():
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    ink = PAL['k'] + (255,)
    tan = PAL['Y'] + (255,)
    for y in range(16):
        for x in range(16):
            d = x + y - 15
            if 1 <= x <= 14 and 1 <= y <= 14:
                if abs(d) <= 1:
                    img.putpixel((x, y), tan)
                elif abs(d) == 2:
                    img.putpixel((x, y), ink)
    # ticks
    for i in range(2, 14, 2):
        x, y = i, 15 - i - 1
        img.putpixel((x, y), ink)
    for x, y in [(1, 12), (2, 13), (12, 1), (13, 2)]:
        img.putpixel((x, y), ink)
    save(img, "tools", "ruler")


def parchment(size=256, seed=7, base=(234, 216, 174)):
    rng = np.random.default_rng(seed)

    def blur(a, r):
        out = a.copy()
        for _ in range(3):
            acc = np.zeros_like(out)
            for dx in range(-r, r + 1):
                acc += np.roll(out, dx, axis=1)
            out = acc / (2 * r + 1)
            acc = np.zeros_like(out)
            for dy in range(-r, r + 1):
                acc += np.roll(out, dy, axis=0)
            out = acc / (2 * r + 1)
        return out

    n = np.zeros((size, size))
    for r, w in [(24, 1.0), (10, 0.6), (4, 0.35), (1, 0.18)]:
        f = blur(rng.standard_normal((size, size)), r)
        f = (f - f.mean()) / (f.std() + 1e-9)
        n += f * w
    n = n / n.std()
    # fibres
    fib = np.zeros((size, size))
    for _ in range(420):
        x, y = rng.integers(0, size, 2)
        ln = rng.integers(6, 30)
        ang = rng.normal(0.15, 0.35)
        for t in range(ln):
            fx = int(x + np.cos(ang) * t) % size
            fy = int(y + np.sin(ang) * t) % size
            fib[fy, fx] += rng.choice([-1, 1]) * 0.6
    fib = blur(fib, 1) * 3
    # stains
    st = blur(rng.standard_normal((size, size)), 40)
    st = (st - st.mean()) / (st.std() + 1e-9)
    v = n * 7 + fib * 5 + np.clip(st, 0, None) * -9
    img = np.zeros((size, size, 4), dtype=np.uint8)
    b = np.array(base, dtype=float)
    tint = np.array([1.0, 0.93, 0.78])
    for c in range(3):
        img[..., c] = np.clip(b[c] + v * tint[c], 0, 255)
    img[..., 3] = 255
    return Image.fromarray(img, "RGBA")


def compass():
    s = 64
    im = Image.new("RGBA", (s * 4, s * 4), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    c = s * 2
    ink = PAL['k'] + (255,)
    red = PAL['r'] + (255,)
    light = PAL['p'] + (255,)
    d.ellipse([c - 88, c - 88, c + 88, c + 88], outline=ink, width=5)
    d.ellipse([c - 74, c - 74, c + 74, c + 74], outline=ink, width=3)
    import math
    for i in range(32):
        a = i * math.pi / 16
        r1 = 74 if i % 4 else 60
        d.line([c + math.cos(a) * r1, c + math.sin(a) * r1, c + math.cos(a) * 88, c + math.sin(a) * 88], fill=ink, width=3)
    # diagonal points
    for k in range(4):
        a = math.pi / 4 + k * math.pi / 2
        tip = (c + math.cos(a) * 70, c + math.sin(a) * 70)
        l = (c + math.cos(a + 1.3) * 16, c + math.sin(a + 1.3) * 16)
        r = (c + math.cos(a - 1.3) * 16, c + math.sin(a - 1.3) * 16)
        d.polygon([tip, l, (c, c)], fill=light, outline=ink)
        d.polygon([tip, r, (c, c)], fill=ink, outline=ink)
    for k in range(4):
        a = -math.pi / 2 + k * math.pi / 2
        tip = (c + math.cos(a) * 110, c + math.sin(a) * 110)
        l = (c + math.cos(a + 1.2) * 22, c + math.sin(a + 1.2) * 22)
        r = (c + math.cos(a - 1.2) * 22, c + math.sin(a - 1.2) * 22)
        fill = red if k == 0 else light
        d.polygon([tip, l, (c, c)], fill=fill, outline=ink)
        d.polygon([tip, r, (c, c)], fill=ink if k else PAL['d'] + (255,), outline=ink)
    d.ellipse([c - 8, c - 8, c + 8, c + 8], fill=PAL['y'] + (255,), outline=ink, width=3)
    im = im.resize((s, s), Image.LANCZOS)
    save(im, "", "compass")


